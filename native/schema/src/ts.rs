//! `assets/js/gen/schema.ts`: ids, enums, the catalog and one row
//! interface per table, for the browser.
//!
//! Row interfaces describe decoded values: an enum is its name, a bool is a
//! boolean, a day is days since 1970-01-01 and a time is unix seconds (both
//! numbers), json is `unknown`, bytes are a `Uint8Array`, and a nullable
//! column is `T | null`.

use crate::model::{Column, Residency, Schema, Type, flag, wire, AS_OF, FREE_PARAM, SOURCE_CELL, TYPES};
use alloc::format;
use alloc::string::String;
use alloc::vec::Vec;

/// A table name as a singular CamelCase type name: `api_keys` is `ApiKey`.
/// `lib/hireme/schema.ex` names row modules by the same rule.
pub fn singular(name: &str) -> String {
    let stem = if let Some(s) = name.strip_suffix("ies") {
        format!("{s}y")
    } else if ["ches", "shes", "xes", "sses"].iter().any(|e| name.ends_with(e)) {
        String::from(&name[..name.len() - 2])
    } else if ["ss", "us", "as"].iter().any(|e| name.ends_with(e)) {
        String::from(name)
    } else if let Some(s) = name.strip_suffix('s') {
        String::from(s)
    } else {
        String::from(name)
    };
    camel(&stem)
}

fn camel(name: &str) -> String {
    name.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            match c.next() {
                Some(f) => f.to_ascii_uppercase().to_string_lossless() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

trait Lossless {
    fn to_string_lossless(self) -> String;
}

impl Lossless for char {
    fn to_string_lossless(self) -> String {
        let mut s = String::new();
        s.push(self);
        s
    }
}

fn json_str(s: &str) -> String {
    let mut out = String::from("\"");
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn opt_str(v: Option<&str>) -> String {
    match v {
        Some(v) => json_str(v),
        None => String::from("null"),
    }
}

fn upper(name: &str) -> String {
    name.to_ascii_uppercase()
}

fn ts_type(s: &Schema, c: &Column) -> String {
    let base = match c.ty {
        Type::Enum => camel(c.target.as_deref().unwrap_or("")),
        Type::Bool => String::from("boolean"),
        Type::Str | Type::Text => String::from("string"),
        Type::Json => String::from("unknown"),
        Type::Bytes => String::from("Uint8Array"),
        _ => String::from("number"),
    };
    let _ = s;
    if c.required { base } else { format!("{base} | null") }
}

fn column_json(c: &Column) -> String {
    format!(
        "{{\"name\":{},\"id\":{},\"type\":{},\"typeCode\":{},\"wire\":{},\"flags\":{},\"required\":{},\"deferred\":{},\"private\":{},\"serverOnly\":{},\"humanOnly\":{},\"readonly\":{},\"unique\":{},\"natural\":{},\"metric\":{},\"metricOf\":{},\"shaOf\":{},\"prose\":{},\"implied\":{},\"ref\":{},\"enum\":{},\"default\":{}}}",
        json_str(&c.name),
        c.id,
        json_str(c.ty.name()),
        c.ty.code(),
        c.wire(),
        c.flags(),
        c.required,
        c.deferred,
        c.private,
        c.server_only,
        c.human_only,
        c.readonly,
        c.unique,
        c.natural,
        c.metric,
        opt_str(c.metric_of.as_deref()),
        opt_str(c.sha_of.as_deref()),
        c.prose,
        c.implied,
        opt_str(if c.ty == Type::Ref { c.target.as_deref() } else { None }),
        opt_str(if c.ty == Type::Enum { c.target.as_deref() } else { None }),
        opt_str(c.default.as_deref()),
    )
}

/// The whole of `assets/js/gen/schema.ts`.
pub fn emit(s: &Schema) -> String {
    let mut o = String::new();
    let mut w = |l: &str| {
        o.push_str(l);
        o.push('\n');
    };
    w("// Generated by `mix hireme.schema` from schema/hireme.schema; do not edit.");
    w("// Row interfaces hold decoded values: an enum by name, a day as days since");
    w("// 1970-01-01, a time as unix seconds, and a nullable column as T | null.");
    w("");
    w(&format!("export const WIRE_HASH = {:#06x};", s.wire_hash));
    w(&format!("export const SCHEMA_REV = {:#010x};", s.schema_rev));
    w(&format!("export const LAYOUT = {};", s.layout));
    w("");

    let domains: Vec<String> = s.domains.iter().map(|d| format!("{}: {}", d.name, d.bit)).collect();
    w(&format!("export const DOMAIN = {{ {} }} as const;", domains.join(", ")));
    w("export type Domain = keyof typeof DOMAIN;");
    w(&format!(
        "export const WIRE_TYPE = {{ null: {}, u32: {}, str: {}, i64: {}, f64: {}, deferred: {}, sym: {}, list: {} }} as const;",
        wire::NULL, wire::U32, wire::STR, wire::I64, wire::F64, wire::DEFERRED, wire::SYM, wire::LIST
    ));
    let codes: Vec<String> = TYPES.iter().map(|(n, t)| format!("{n}: {}", t.code())).collect();
    w(&format!("export const TYPE_CODE = {{ {} }} as const;", codes.join(", ")));
    w(&format!(
        "export const FLAG = {{ required: {}, deferred: {}, private: {}, serverOnly: {}, humanOnly: {}, readonly: {}, unique: {}, metric: {}, prose: {}, implied: {}, metricOn: {}, natural: {}, cascade: {}, shaOn: {}, loose: {} }} as const;",
        flag::REQUIRED, flag::DEFERRED, flag::PRIVATE, flag::SERVER_ONLY, flag::HUMAN_ONLY, flag::READONLY,
        flag::UNIQUE, flag::METRIC, flag::PROSE, flag::IMPLIED, flag::METRIC_ON, flag::NATURAL, flag::CASCADE, flag::SHA_ON, flag::LOOSE
    ));
    let frames: Vec<String> = s.frames.iter().map(|f| format!("{}: {}", f.name, f.id)).collect();
    w(&format!("export const FRAME = {{ {} }} as const;", frames.join(", ")));
    w(&format!("export const AS_OF = {AS_OF:#06x};"));
    w(&format!("export const SOURCE = {SOURCE_CELL:#06x};"));
    w(&format!("export const FREE_PARAM = {FREE_PARAM:#06x};"));
    w("");

    for e in &s.enums {
        let values: Vec<String> = e.values.iter().map(|v| json_str(v)).collect();
        w(&format!("export const {} = [{}] as const;", upper(&e.name), values.join(", ")));
        w(&format!("export type {} = (typeof {})[number];", camel(&e.name), upper(&e.name)));
    }
    let names: Vec<String> = s.enums.iter().map(|e| format!("{}: {}", e.name, upper(&e.name))).collect();
    w(&format!(
        "export const ENUMS: {{ readonly [name: string]: readonly string[] }} = {{ {} }};",
        names.join(", ")
    ));
    w("");

    let ids: Vec<String> = s.tables.iter().map(|t| format!("{}: {}", t.name, t.id)).collect();
    w(&format!("export const TABLE_ID = {{ {} }} as const;", ids.join(", ")));
    w("export type TableName = keyof typeof TABLE_ID;");
    let cids: Vec<String> = s.commands.iter().map(|c| format!("{}: {}", c.name, c.id)).collect();
    w(&format!("export const COMMAND_ID = {{ {} }} as const;", cids.join(", ")));
    w("export type CommandName = keyof typeof COMMAND_ID;");
    w("");

    w("export interface ColumnDef {");
    w("  name: string; id: number; type: keyof typeof TYPE_CODE; typeCode: number; wire: number; flags: number;");
    w("  required: boolean; deferred: boolean; private: boolean; serverOnly: boolean; humanOnly: boolean;");
    w("  readonly: boolean; unique: boolean; natural: boolean; metric: boolean; metricOf: string | null; shaOf: string | null;");
    w("  prose: boolean; implied: boolean; ref: string | null; enum: string | null; default: string | null;");
    w("}");
    w("export interface KeyDef { cols: string[]; global: boolean; where: string | null; }");
    w("export interface TableDef {");
    w("  id: number; name: string; domain: Domain; residency: \"resident\" | \"server\" | \"wire\" | \"projection\";");
    w("  cap: number | null; appendOnly: boolean; softDelete: boolean; global: boolean; accountOptional: boolean;");
    w("  singleton: boolean; natural: KeyDef[]; source: string | null; cols: ColumnDef[];");
    w("}");
    w("export interface ParamDef { name: string; id: number; type: keyof typeof TYPE_CODE; typeCode: number; wire: number; required: boolean; column: boolean; ref: string | null; enum: string | null; }");
    w("export interface CommandDef { id: number; name: string; table: string; humanOnly: boolean; params: ParamDef[]; }");
    w("");

    // One JSON object, one table per line: `mix hireme.schema --check` reads
    // it back to refuse a renumbered column.
    w("export const TABLES: { readonly [T in TableName]: TableDef } = {");
    for t in &s.tables {
        let naturals: Vec<String> = t
            .naturals
            .iter()
            .map(|k| {
                let cols: Vec<String> = k.cols.iter().map(|c| json_str(c)).collect();
                format!("{{\"cols\":[{}],\"global\":false,\"where\":{}}}", cols.join(","), opt_str(k.where_.as_deref()))
            })
            .collect();
        let cols: Vec<String> = t.cols.iter().map(column_json).collect();
        w(&format!(
            "  {}: {{\"id\":{},\"name\":{},\"domain\":{},\"residency\":{},\"cap\":{},\"appendOnly\":{},\"softDelete\":{},\"global\":{},\"accountOptional\":{},\"singleton\":{},\"natural\":[{}],\"source\":{},\"cols\":[{}]}},",
            json_str(&t.name),
            t.id,
            json_str(&t.name),
            json_str(&t.domain),
            json_str(t.residency.name()),
            t.cap.map_or(String::from("null"), |c| format!("{c}")),
            t.append_only,
            t.soft_delete,
            t.global,
            t.account_optional,
            t.singleton,
            naturals.join(","),
            opt_str(t.source.as_deref()),
            cols.join(",")
        ));
    }
    w("};");
    w("");

    w("export const COMMANDS: { readonly [C in CommandName]: CommandDef } = {");
    for c in &s.commands {
        let params: Vec<String> = c
            .params
            .iter()
            .map(|p| {
                format!(
                    "{{\"name\":{},\"id\":{},\"type\":{},\"typeCode\":{},\"wire\":{},\"required\":{},\"column\":{},\"ref\":{},\"enum\":{}}}",
                    json_str(&p.name),
                    p.id,
                    json_str(p.ty.name()),
                    p.ty.code(),
                    p.wire(),
                    p.required,
                    p.column,
                    opt_str(if p.ty == Type::Ref { p.target.as_deref() } else { None }),
                    opt_str(if p.ty == Type::Enum { p.target.as_deref() } else { None }),
                )
            })
            .collect();
        w(&format!(
            "  {}: {{\"id\":{},\"name\":{},\"table\":{},\"humanOnly\":{},\"params\":[{}]}},",
            json_str(&c.name),
            c.id,
            json_str(&c.name),
            json_str(&c.table),
            c.human_only,
            params.join(",")
        ));
    }
    w("};");
    w("");

    for t in &s.tables {
        let kind = match t.residency {
            Residency::Resident => "resident",
            Residency::Server => "server-side",
            Residency::Wire => "derived on the wire",
            Residency::Projection => "a resident projection",
        };
        w(&format!("/** `{}`: {kind}. */", t.name));
        w(&format!("export interface {} {{", singular(&t.name)));
        // A server_only column never reaches a client, so no row has it.
        for c in t.cols.iter().filter(|c| !c.server_only) {
            w(&format!("  {}: {};", c.name, ts_type(s, c)));
        }
        w("}");
    }
    o
}
